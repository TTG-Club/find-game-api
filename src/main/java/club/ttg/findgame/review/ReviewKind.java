package club.ttg.findgame.review;

/**
 * Направление оценки.
 *
 * Различает не только автора, но и правила показа: отзыв о мастере читают все,
 * отзыв об игроке — только мастер, к которому тот подал заявку.
 */
public enum ReviewKind {

    /** Игрок о мастере. */
    MASTER_REVIEW,

    /** Мастер об игроке. */
    PLAYER_REVIEW
}
