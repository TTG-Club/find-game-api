package club.ttg.findgame.membership;

/**
 * Кем пользователь приходится игре. Нужна соседним сервисам, которые строят
 * своё поверх игры, — например, бастионам в core-api.
 */
public enum GameRole {
    /** Мастер игры — её владелец. */
    MASTER,
    /** Игрок с одобренной заявкой. */
    PLAYER,
    /** Ни то, ни другое: заявки нет, она не разобрана или отклонена. */
    NONE
}
